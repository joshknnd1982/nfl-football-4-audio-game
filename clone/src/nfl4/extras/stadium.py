"""The stadium sounds of the N. F. L. rules mode: the crowd, the impacts, the first-down chain, the goal post (nfl4 only, rule 0.13). This is
inspired by Jim Kitchen.

SY.2 (the owner's list after the S8.2 playtest: realistic sound effects and crowd effects), playbook 7.7.1 and 7.8, D-102. About twenty short
sounds are shipped beside the original's wavs in assets/sounds_nx/ (GENERATED by work/s82/make_sfx.py: new original work, MIT, nothing is a
recording of anything) and are played on the extra channel at moments the game already knows:

  a touchdown                  the crowd cheers (yours) or groans (the other team's); after a field goal of yours, applause; the other team's, a sigh
  a turnover, a sack           the crowd groans when it is your team's, roars when it is the other team's; a sack also hits (a helmet)
  a gain of 20 yards or more   the crowd roars; a gain of 8 yards or more also hits (pads); a completed pass has the pop of the catch
  a first down                 the chain clanks
  a missed field goal          now and then the ball hits the goal post
  a penalty                    the crowd boos when the flag is on your team; the flag is thrown when it is on the other
  the end of the first and third quarters, and half time    applause

Nothing here changes the game: every choice (which file of a family, whether the post is hit) draws from the stadium's OWN random generator,
nothing waits for a sound, the sounds are quiet (they never cover speech: -17 to -24 dB under the sound volume), and the Classic rules never call
it. A player's file with the same name in the sounds folder replaces the shipped one, and a family grows by numbers (crowd_cheer2.wav,
crowd_cheer3.wav ...): the stadium draws among the files of a family (rule 0.14). F9, Rules, Stadium sounds switches all of it off.

SZ.2 (D-107, the owner: "ensure the user can customize them by adding custom wav files"): F9, Sounds, Stadium and referee sounds
(extras/stadium_menu.py) lists the nineteen sounds (ALL_NAMES: these, the referee's clicks and the whistles) with the file name each takes, the
check reads the player's files (`check_files`), `put_back` moves them aside, a file may be a wav, ogg, flac or mp3, and a file that cannot be used
is skipped for the shipped sound (`Stadium.files`).
"""
from __future__ import annotations

import logging
import os
import random
import re

from ..data import paths
from ..game import outcome as O
from ..game.gamestate import other
from ..game.rnd import GameRandom
from ..speech.roles import REFEREE

log = logging.getLogger("nfl4.extras")

FOLDER = "sounds_nx"                      # beside the original's assets/sounds in the program folder
SEED_MIX = 0x57AD_1A70
LEVELS = {"crowd_cheer": -1900, "crowd_roar": -2100, "crowd_groan": -2100, "crowd_boo": -2300, "crowd_gasp": -2200, "crowd_applause": -2200,
          "crowd_oh": -2200, "hit_helmet": -1700, "hit_pads": -1900, "ball_catch": -2000, "flag_throw": -2200, "first_down_chain": -2400,
          "goal_post_hit": -1900}                       # hundredths of a decibel under the sound volume
LEVELS.update({"mic_on": -2000, "mic_off": -2200})
NAMES = tuple(LEVELS)
WHISTLES = ("whistle_short", "whistle_long", "whistle_double", "whistle_triple")      # SY.3: the pea whistles, in the whistle hook of GameSounds
ALL_NAMES = NAMES + WHISTLES                                      # the nineteen sounds a player can replace (SZ.2): the list in F9, Sounds
LABEL_IDS = {name: "NXB-S%02d" % (n + 1) for n, name in enumerate(ALL_NAMES)}     # their plain-word names (strings_nx.tsv)
WHISTLE_LEVEL = -1500                                             # the whistle's level in the game: the tackle's (GameSounds.play_tackle)
CONTEXT_WHISTLES = {"final": "whistle_long", "quarter": "whistle_long", "twominute": "whistle_double", "timeout": "whistle_short",
                    "penalty": "whistle_long", "review": "whistle_double"}
DEFAULT_WHISTLES = ("whistle_short",) * 5 + ("whistle_double",) * 2 + (None,) * 3        # no context: a pea whistle seven times in ten
BIG_GAIN, HIT_GAIN = 20, 8
POST_CHANCE = 25                                         # percent of the missed field goals that hit the post
CATCH_CHANCE = 60                                        # percent of the completions that have the pop of the catch
_FAMILY = re.compile(r"^(?P<name>[a-z_]+?)(?P<n>\d*)(?P<ext>\.(?:wav|ogg|flac|mp3))$", re.IGNORECASE)
_EXTENSION_ORDER = {".wav": 0, ".ogg": 1, ".flac": 2, ".mp3": 3}      # the sound layer reads these (audio/wavdata.DECODER_EXTENSIONS)


def shipped_folder() -> str:
    return os.path.join(paths.program_dir(), "assets", FOLDER)


def player_folder() -> str:
    return os.path.join(paths.user_data_dir(), "sounds")


def family(name: str, folders: tuple[str, ...]) -> list[str]:
    """The files of a sound family: name.wav and name2.wav, name3.wav ... in the folders, the player's folder first (a file of the same
    number there replaces the shipped one, a new number adds one: rule 0.14). A player's file may be a wav, ogg, flac or mp3 (SZ.2, D-107);
    two files of one number in a folder (crowd_cheer2.wav and crowd_cheer2.ogg) count once, the wav first."""
    found: dict[str, str] = {}
    for folder in reversed(folders):
        try:
            entries = sorted(os.listdir(folder))
        except OSError:
            continue
        here: dict[str, tuple[int, str]] = {}
        for entry in entries:
            match = _FAMILY.match(entry)
            if match and match.group("name").lower() == name:
                key = (match.group("n") or "1").lstrip("0") or "1"
                rank = _EXTENSION_ORDER[match.group("ext").lower()]
                if key not in here or rank < here[key][0]:
                    here[key] = (rank, os.path.join(folder, entry))
        found.update({key: path for key, (rank, path) in here.items()})
    return [found[key] for key in sorted(found, key=int)]


def mine(files: list[str], folder: str | None = None) -> list[str]:
    """The files of a family that are the player's (in the player's sounds folder)."""
    where = os.path.normcase(os.path.abspath(folder or player_folder()))
    return [f for f in files if os.path.normcase(os.path.abspath(os.path.dirname(f))) == where]


def put_back(player_dir: str | None = None):
    """The player's stadium, referee and whistle files are moved (never deleted) to the removed sounds folder, so the shipped sounds play
    again (F9, Sounds, Put the stadium sounds back). Returns audio.restore.RestoreResult."""
    from ..audio import restore
    folder = player_dir or player_folder()
    result = restore.RestoreResult()
    names = []
    try:
        entries = sorted(os.listdir(folder))
    except OSError:
        return result
    for entry in entries:
        match = _FAMILY.match(entry)
        if match and match.group("name").lower() in ALL_NAMES and os.path.isfile(os.path.join(folder, entry)):
            names.append(entry)
    restore._move_aside(folder, names, result)
    log.info("stadium: the player's sounds were put back: %s", result)
    return result


def check_files(library, player_dir: str | None = None) -> int:
    """Read every file the player put in a family of the stadium, so a damaged one is reported (the library logs it and the Sounds menu's
    check counts it). Returns how many cannot be used."""
    folder = player_dir or player_folder()
    bad = 0
    for name in ALL_NAMES:
        for path in family(name, (folder,)):              # only the player's folder: the shipped sounds are ours
            if library.pick_file(path).sound is None:
                bad += 1
    return bad


class Stadium:
    def __init__(self, rules, on: bool = False):
        self.rules = rules
        self.on = bool(on)
        self.game = None
        self.rnd: GameRandom | None = None
        self.folders = (player_folder(), shipped_folder())
        self.played = 0

    def attach(self, game, state) -> None:
        self.game = game
        seed = getattr(getattr(game, "rnd", None), "seed", None)
        self.rnd = GameRandom(random.Random((seed if seed is not None else 0x5EED) ^ SEED_MIX))
        self.played = 0
        self.last_mic = -99.0
        sounds = getattr(game, "sounds", None)
        if sounds is not None and self.on:
            sounds.whistle_hook = self.whistle           # SY.3: asked at every whistle; it answers None when this is not an N. F. L. rules game
        speech = getattr(game, "speech", None)
        if speech is not None and hasattr(speech, "set_role_effect"):
            speech.set_role_effect(REFEREE, "pa" if self.on else None)      # the referee's microphone is rendered speech with a public-address sound

    def active(self) -> bool:
        """The stadium is on, the sounds exist, and the game being played is the one this stadium was made for (a Classic game, or the program
        between two games, must hear none of it: the whistle hook lives on the sounds, which outlive a game)."""
        engine = getattr(self.game, "play_engine", None)
        return bool(self.on and self.rnd is not None and getattr(self.game, "sounds", None) is not None
                    and engine is not None and getattr(engine, "rules", None) is self.rules)

    def files(self, name: str) -> list[str]:
        """The sounds of a family that can be used: the player's files that the sound layer reads, else the shipped ones (a damaged file of the
        player's never makes a silence where a sound belongs: it is skipped, the library logs it and says its one notice, SZ.2)."""
        files = family(name, self.folders)
        library = getattr(getattr(getattr(self.game, "sounds", None), "audio", None), "library", None)
        if library is None:
            return files
        usable = [path for path in files if library.pick_file(path).sound is not None]
        return usable or family(name, (self.folders[-1],))

    def play(self, name: str) -> None:
        """One sound of the family, on the extra channel, nothing waits for it."""
        if not self.active():
            return
        files = self.files(name)
        if not files:
            log.debug("stadium: no file for %s", name)
            return
        path = files[self.rnd(len(files)) - 1] if len(files) > 1 else files[0]
        self.game.sounds.play_effect(path, LEVELS[name])
        self.played += 1

    def whistle(self, context) -> str | None:
        """The pea whistle for a whistle of the game (the path of a file of its family), or None for the original's foot11."""
        if not self.active():
            return None
        name = CONTEXT_WHISTLES.get(context) if context else DEFAULT_WHISTLES[self.rnd(len(DEFAULT_WHISTLES)) - 1]
        if name is None:
            return None
        files = self.files(name)
        if not files:
            return None
        return files[self.rnd(len(files)) - 1] if len(files) > 1 else files[0]

    def mic(self, opening: bool) -> None:
        """The click of the referee's microphone: when it opens (not twice within three seconds) and when it closes."""
        if not self.active():
            return
        now = self.game.sounds.clock() if hasattr(self.game.sounds, "clock") else 0.0
        if opening:
            if now - self.last_mic < 3.0:
                return
            self.last_mic = now
            self.play("mic_on")
        else:
            self.last_mic = now
            self.play("mic_off")

    # ----- what the engine tells -----

    def note_outcome(self, state, outcome) -> None:
        """The narration of a play has ended: the impact and the catch."""
        if not self.active() or outcome.two_point_try:
            return
        kind, yards = outcome.kind, outcome.yards
        if kind == O.SACK:
            self.play("hit_helmet")
        elif kind == O.RUN and yards >= HIT_GAIN:
            self.play("hit_pads")
        elif kind == O.PASS_COMPLETE:
            if yards >= HIT_GAIN:
                self.play("hit_pads")
            elif self.rnd(100) <= CATCH_CHANCE:
                self.play("ball_catch")
        elif kind in (O.FIELD_GOAL_MISSED, O.FIELD_GOAL_SHORT) and self.rnd(100) <= POST_CHANCE:
            self.play("goal_post_hit")

    def between(self, state, facts) -> None:
        """After the down sentence: the crowd's answer to the last play, and the chain."""
        if not self.active() or facts is None or facts.two_point or facts.taken_over:
            return
        side = facts.offense
        mine = side == 1
        if facts.turnover and facts.kind in (O.INTERCEPTION, O.FUMBLE):
            self.play("crowd_groan" if mine else "crowd_roar")
        elif facts.kind == O.SACK:
            self.play("crowd_groan" if mine else "crowd_roar")
        elif facts.kind in (O.RUN, O.PASS_COMPLETE) and facts.yards >= BIG_GAIN and not facts.score:
            self.play("crowd_roar" if mine else "crowd_gasp")
        elif facts.kind in (O.FIELD_GOAL_MISSED, O.FIELD_GOAL_SHORT):
            self.play("crowd_groan" if mine else "crowd_oh")
        elif facts.kind in (O.RUN, O.PASS_COMPLETE) and facts.yards >= facts.to_go and not facts.score and not facts.turnover:
            self.play("first_down_chain")

    def moment(self, state, what: str, quarter: int = 0) -> None:
        if not self.active():
            return
        if what == "touchdown":
            self.play("crowd_cheer" if state.wisoff == 1 else "crowd_groan")
        elif what == "score":
            if state.points == 3:
                self.play("crowd_applause" if state.wisoff == 1 else "crowd_oh")
        elif what == "quarter_end" and quarter in (1, 3):
            self.play("crowd_applause")
        elif what == "half_time":
            self.play("crowd_applause")

    def penalty(self, state, side: int) -> None:
        if not self.active():
            return
        self.play("crowd_boo" if side == 1 else "flag_throw")
