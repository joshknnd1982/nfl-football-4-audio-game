def text(text_id: str, **values) -> str:
    """The text with its placeholders filled: text("NXT-02", n=2) gives " they have 2 time outs left. "."""
    result = TEXTS[text_id]
    for name, value in values.items():
        result = result.replace("<%s>" % name, str(value)).replace("<%s>" % name.replace("_", " "), str(value))
    return result
