"""Every text of the hot-key menus and the season prompts is a string of the original's exe. This is inspired by Jim Kitchen.

game/prompt_texts.py (typed from the lifted lines), game/help_texts.py (generated by work/make_help_texts_s74a.py from the
lifted speckeys, readins and SayHints, D-017) and the speakers' names of speech/roles.py, each checked against
spec/strings_all.tsv; B-T40: no name of a text module is assigned twice.
"""
import ast
import collections
import importlib.util

from nfl4.game import help_texts as H
from nfl4.game import prompt_texts as T
from nfl4.speech.roles import F11_NAMES
from specfiles import GAME_ROOT, need, original_strings, strings_table


def module_texts(module):
    return {name: value for name, value in vars(module).items()
            if not name.startswith("_") and isinstance(value, str) and name.isupper()}


def test_every_short_text_is_a_string_of_the_original():
    strings = original_strings()
    texts = module_texts(T)
    assert [(n, t) for n, t in texts.items() if t not in strings] == []
    assert len(texts) == 37
    assert [w for w in T.PLAYOFF_WEEK_NAMES.values() if w not in strings] == []


def test_the_volume_menu_names_its_speakers_with_the_originals_words():
    rows = {row["text"]: row["procedures"] for row in strings_table()}
    assert all("p_421960" in rows[name] for name in F11_NAMES.values())


def test_every_help_piece_is_a_string_of_its_procedure():
    rows = {}
    for row in strings_table():
        rows.setdefault(row["text"], set()).update(p for p in row["procedures"].split(",") if p)
    owners = {"SPECIAL_KEYS": "p_420860", "GAME_INSTRUCTIONS": "p_420040", "FOOTBALL_INSTRUCTIONS": "p_420040",
              "TERMINOLOGY": "p_420b50"}
    for name, procedure in owners.items():
        pieces = getattr(H, name + "_PIECES")
        assert [p for p in pieces if procedure not in rows.get(p, set())] == [], name
        assert getattr(H, name + "_ORIGINAL", getattr(H, name)) == getattr(H, name + "_JOINER").join(pieces)
    assert sum(len(getattr(H, n + "_PIECES")) for n in owners) == 103


def test_the_help_module_is_what_the_generator_writes_from_the_lifted_code():
    script = need(GAME_ROOT / "work" / "make_help_texts_s74a.py")
    need(GAME_ROOT / "work" / "lift")
    spec = importlib.util.spec_from_file_location("make_help_texts_s74a", script)
    generator = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(generator)
    written = generator.OUT.read_text(encoding="utf-8")
    generator.OUT = GAME_ROOT / "work" / "help_texts_check.tmp"
    try:
        assert generator.main(write=True) == 0
        assert generator.OUT.read_text(encoding="utf-8") == written
    finally:
        generator.OUT.unlink(missing_ok=True)


def test_no_name_of_the_text_modules_is_assigned_twice():
    for module in (T, H):
        tree = ast.parse(open(module.__file__, encoding="utf-8").read())
        names = collections.Counter(n.id for node in tree.body if isinstance(node, ast.Assign)
                                    for target in node.targets for n in ast.walk(target) if isinstance(n, ast.Name))
        assert [name for name, count in names.items() if count > 1] == [], module.__name__
