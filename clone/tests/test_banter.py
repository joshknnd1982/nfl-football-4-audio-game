"""The announcer's banter: the 142 lines and the draw (GAME_SPEC 5.13, Q37, Q38; D-028 item 3). This is inspired by Jim Kitchen.

game/banter_lines.py is generated by work/make_banter_module_s73b.py; here it is compared with the generated table of
GAME_SPEC 5.13 and the strings of the exe, and the GoSub 0x45915e is run on the rig with strict scripted draws derived
from the lifted text: the line Int(Rnd * 142) + 1 (again while used), the name Int(Rnd * 58) + 1, rady's Int(Rnd * 30),
then the alternative of lines 101 and 110.
"""
import random
import re

import pytest

from gamerig import Rig
from nfl4.game.banter import line_texts, speak_banter
from nfl4.game.banter_lines import LINES, NAME, OPPONENT_QB
from nfl4.game.gamestate import GameState
from nfl4.speech.roles import ANNOUNCER
from randsources import ScriptedRandom, below_value, value_for
from specfiles import SPEC, original_strings, read_spec, strings_of_class


def spec_banter_rows():
    text = read_spec(SPEC / "GAME_SPEC.md")
    block = text[text.index("<!-- BANTER-TABLE-BEGIN -->"):text.index("<!-- BANTER-TABLE-END -->")]
    rows = {}
    for line in block.split("\n"):
        match = re.match(r'^\| (\d+) \| "(.*)" \| (.*) \| (.*) \|$', line)
        if match:
            rows[int(match.group(1))] = (match.group(2), match.group(3), match.group(4))
    return rows


def test_the_module_has_the_142_lines_of_the_spec_table_text_for_text():
    rows = spec_banter_rows()
    assert sorted(rows) == list(range(1, 143)) and len(LINES) == 142
    for line in LINES:
        first, second_cell, notes = rows[line.number]
        assert line.first == first
        if line.alternatives:
            assert second_cell == " or ".join('"%s"' % a for a in line.alternatives)
        elif line.second:
            assert second_cell == '"%s"' % line.second
        else:
            assert second_cell == ""
        assert ("twice" in notes) == (line.bleeps == 2)
        assert ("bleep" in notes) == (line.bleeps > 0)
        assert ("faster" in notes) == (line.rate_step == 1)


def joins(piece: str, parts: set[str]) -> bool:
    """True when piece is a concatenation of strings of `parts` (the lifted lines join up to three of them)."""
    reachable = [True] + [False] * len(piece)
    for end in range(1, len(piece) + 1):
        reachable[end] = any(reachable[start] and piece[start:end] in parts for start in range(end))
    return reachable[-1]


def test_every_piece_of_every_line_is_joined_from_banter_strings_of_the_original():
    parts = set(strings_of_class("ANNOUNCER-BANTER"))
    assert len(parts) == 196
    # a few lines join a piece the play-by-play shares (line 24 " ", line 51 " runs "): any string of the exe
    parts |= original_strings()
    for line in LINES:
        for text in (line.first, line.second) + line.alternatives:
            for piece in text.replace(OPPONENT_QB, NAME).split(NAME):
                if piece:
                    assert joins(piece, parts), (line.number, piece)


def test_the_name_is_the_same_in_both_texts_and_the_alternative_is_chosen():
    line9 = LINES[8]
    assert line_texts(line9, "Smith", "Starr", None) == (" The helmet of Smith is rolling around on the field ",
                                                         " I hope that his head isn't in it ")
    assert line_texts(LINES[44], "Smith", "Starr", None)[0] == " A fan just hit Starr in the head with a dog bone "
    assert line_texts(LINES[100], "x", "y", 4) == ("Ghip, have you stopped", "cross dressing in public?")
    assert line_texts(LINES[109], "x", "y", 1)[1] == "make lemonade"


# ----- the GoSub on the rig -----

def banter_rig(tmp_path, values, comments_off=False):
    rig = Rig(sounds_dir=tmp_path / "sounds", rng=ScriptedRandom(values, strict=True))
    rig.rnd.trace = []
    rig.game.comtog_source = lambda: 1 if comments_off else 0
    state = GameState()
    state.banter_names = ["N%d" % i for i in range(1, 59)]
    state.quarterbacks = {1: "Starr", 2: "Unitas"}
    return rig, state


def test_one_call_draws_line_name_and_pause_in_that_order_and_speaks_the_line(tmp_path):
    rig, state = banter_rig(tmp_path, [value_for(142, 1), value_for(58, 7), below_value(30, 0)])
    speak_banter(rig.game, state)
    assert rig.rnd.trace == [142, 58, 30]
    assert rig.said == [(" It looks like N7 is shaken up on the play ", ANNOUNCER, 0)]
    assert [kind for kind, _ in rig.sapi.events if kind in ("speak", "wait")] == ["speak", "wait"]   # say waits
    assert state.banter_used == [1]


def test_a_used_line_is_drawn_again_and_the_history_lives_in_the_state(tmp_path):
    rig, state = banter_rig(tmp_path, [value_for(142, 2), value_for(142, 1), value_for(58, 1), below_value(30, 3)])
    state.banter_used = [2]
    speak_banter(rig.game, state)
    assert rig.rnd.trace == [142, 142, 58, 30] and state.banter_used == [2, 1]


def test_lines_101_and_110_draw_their_second_text_after_the_pause(tmp_path):
    rig, state = banter_rig(tmp_path, [value_for(142, 101), value_for(58, 1), below_value(30, 0), value_for(5, 2)])
    speak_banter(rig.game, state)
    assert rig.rnd.trace == [142, 58, 30, 5]
    assert [t for t, _, _ in rig.said] == ["Ghip, have you stopped", "beating your wife?"]


def test_line_75_bleeps_twice_line_113_is_one_rate_step_faster(tmp_path):
    rig, state = banter_rig(tmp_path, [value_for(142, 75), value_for(58, 1), below_value(30, 0),
                                       value_for(142, 113), value_for(58, 1), below_value(30, 0)])
    speak_banter(rig.game, state)
    bleeps = [e for e in rig.slot_log if e.action == "play"]
    assert [e.sound_id for e in bleeps] == ["snd_foot13", "snd_foot13"]
    speak_banter(rig.game, state)
    assert rig.said[-1][2] == 1 and rig.said[0][2] == 0


def test_with_comments_off_nothing_is_drawn_said_or_played(tmp_path):
    rig, state = banter_rig(tmp_path, [], comments_off=True)
    speak_banter(rig.game, state)
    assert rig.rnd.trace == [] and rig.said == [] and rig.slot_log == []


def test_after_all_142_lines_nothing_more_is_said(tmp_path):
    rig, state = banter_rig(tmp_path, [])
    state.banter_used = list(range(1, 143))
    speak_banter(rig.game, state)
    assert rig.rnd.trace == [] and rig.said == []


def test_a_game_long_sequence_never_repeats_a_line(tmp_path):
    rig = Rig(sounds_dir=tmp_path / "sounds", rng=random.Random(9))
    state = GameState()
    state.banter_names = ["N%d" % i for i in range(1, 59)]
    state.quarterbacks = {1: "Starr", 2: "Unitas"}
    for _ in range(142):
        speak_banter(rig.game, state)
    assert sorted(state.banter_used) == list(range(1, 143)) and rig.rnd.fallbacks == 0
